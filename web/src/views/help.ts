import { h } from '../dom.js';

export function renderHelp(view: HTMLElement): void {
  view.append(
    h('h1', { class: 'view-title' }, 'ヘルプ'),
    h('p', { class: 'view-lead' }, 'CryptBox のしくみと、使うときの注意点。'),

    h(
      'div',
      { class: 'card prose' },
      h('h3', {}, '鍵はどこにありますか？'),
      h(
        'p',
        {},
        '共有リンクの「#」より後ろが復号鍵です。ブラウザの仕様上、「#」以降はサーバーに送信されません。つまり運営者もファイルの中身を復元できません。',
      ),

      h('h3', {}, '暗号化の内容'),
      h('ul', {},
        h('li', {}, 'ファイル本体: AES-256-GCM（16 MiB のチャンクごとに暗号化）'),
        h('li', {}, 'パスワード: Argon2id（m=64 MiB, t=3, p=1）で鍵に伸長'),
        h('li', {}, '鍵のラップ: HKDF-SHA256 でリンクの秘密とパスワードを混ぜた KEK'),
        h('li', {}, '通信: TLS 1.3'),
      ),

      h('h3', {}, 'パスワードを付けるとどうなりますか？'),
      h(
        'p',
        {},
        'リンクとパスワードの二要素になります。リンクだけが漏れても復号できません。入力を間違えた場合はブラウザ内で判定するので、ダウンロード回数は減りません。',
      ),

      h('h3', {}, '画質・音質は落ちませんか？'),
      h(
        'p',
        {},
        'サーバーからは暗号化されたバイト列にしか見えないため、再圧縮や変換が起こりようがありません。受信時は認証タグ付きで復号するので、1 バイトでも変化していれば失敗として検出されます。',
      ),

      h('h3', {}, '大きなファイルはどう扱われますか？'),
      h(
        'p',
        {},
        '16 MiB ずつに分けて並列に送ります。ダウンロードは復号しながらそのままディスクへ書き出すので、ファイル全体をメモリに載せません。通信が切れても、最後に復号できた位置から再開します。',
      ),

      h('h3', {}, 'できないこと'),
      h('ul', {},
        h('li', {}, 'リンクを紛失した場合の復旧（鍵がサーバーにないため不可能です）'),
        h('li', {}, 'ウイルススキャン（中身が見えないため原理的にできません）'),
        h('li', {}, '受信トレイやアカウント管理（本アプリはアカウントを持ちません）'),
      ),
    ),
  );
}
